function hash(s) {
    let h = 0;
    for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
    return h;
}

function pickImages(slug, category) {
    const pool = POOLS[category] || FALLBACK_POOL;
    const i = hash(slug) % pool.length;
    const main = pool[i];
    const others = [pool[(i + 1) % pool.length], pool[(i + 2) % pool.length]];
    return { photoId: main, galleryIds: [main].concat(others) };
}

function popularity(reviews) {
    if (reviews >= 800) return "very_high";
    if (reviews >= 400) return "high";
    if (reviews >= 150) return "medium";
    return "low";
}

function unique(arr) {
    const seen = new Set();
    const out = [];
    (arr || []).forEach(function (x) {
        if (x === undefined || x === null) return;
        const k = String(x);
        if (!seen.has(k)) { seen.add(k); out.push(x); }
    });
    return out;
}

function mergeText(existing, incoming) {
    const seen = new Set(existing || []);
    const out = (existing || []).slice();
    (incoming || []).forEach(function (x) {
        if (x === undefined || x === null) return;
        const k = String(x).trim().toLowerCase();
        if (!seen.has(k)) { seen.add(k); out.push(x); }
    });
    return out;
}

function photoIdFromUrl(url) {
    const m = /images\.unsplash\.com\/([^?]+)\?/.exec(url || "");
    return m ? m[1] : "";
}

function idsFromUrls(urls) {
    return (urls || []).map(photoIdFromUrl).filter(Boolean);
}

function imageWidthFromUrl(url) {
    const m = /&w=(\d+)/.exec(url || "");
    return m ? Number(m[1]) : 1200;
}

